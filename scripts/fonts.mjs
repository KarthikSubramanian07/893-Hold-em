// Trim Shippori Mincho B1 to the subsets this UI actually draws.
//
// Fontsource ships the Japanese face as ~120 unicode-range slices per weight;
// declaring all of them costs ~150 kB of render-blocking CSS per weight. The
// UI's kanji are a fixed set, so we scan the client source for CJK characters
// and keep only the slices that contain them, plus Latin. Anything else (a
// kanji player name, say) falls back to the system Mincho.
//
//   node scripts/fonts.mjs        # rewrite src/client/styles/fonts.css
//   node scripts/fonts.mjs --check  # exit 1 if it is stale (CI)
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const out = join(root, 'src/client/styles/fonts.css');
const WEIGHTS = [500, 800];
const PKG = '@fontsource/shippori-mincho-b1';
const CJK = /[　-ヿ㐀-䶿一-鿿＀-￯]/gu;

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : /\.(tsx?|css)$/.test(f) ? [p] : [];
  });
}

const used = new Set();
for (const file of [...walk(join(root, 'src')), join(root, 'index.html')]) {
  if (file === out) continue;
  for (const ch of readFileSync(file, 'utf8').match(CJK) ?? []) used.add(ch.codePointAt(0));
}

function covers(range, cps) {
  return range.split(',').some((part) => {
    const m = /U\+([0-9a-f]+)(?:-([0-9a-f]+))?/i.exec(part.trim());
    if (!m) return false;
    const lo = parseInt(m[1], 16);
    const hi = m[2] ? parseInt(m[2], 16) : lo;
    for (const cp of cps) if (cp >= lo && cp <= hi) return true;
    return false;
  });
}

let css = `/* Generated by scripts/fonts.mjs from ${PKG}. Do not edit by hand. */\n/* Kanji in use: ${[...used].sort((a, b) => a - b).map((c) => String.fromCodePoint(c)).join('')} */\n`;
let kept = 0;
for (const w of WEIGHTS) {
  const src = readFileSync(join(root, 'node_modules', PKG, `${w}.css`), 'utf8');
  for (const block of src.split(/(?=\/\* shippori)/)) {
    if (!block.includes('@font-face')) continue;
    const name = /\/\* (\S+) \*\//.exec(block)?.[1] ?? '';
    const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1] ?? '';
    if (name.includes('-latin-') || covers(range, used)) {
      css += block.replaceAll('url(./files/', `url(${PKG}/files/`).trim() + '\n\n';
      kept++;
    }
  }
}

if (process.argv.includes('--check')) {
  const current = readFileSync(out, 'utf8');
  if (current !== css) {
    console.error('src/client/styles/fonts.css is stale. Run: node scripts/fonts.mjs');
    process.exit(1);
  }
  console.log('fonts.css is current');
} else {
  writeFileSync(out, css);
  console.log(`kept ${kept} font-face slices for ${used.size} CJK characters`);
}

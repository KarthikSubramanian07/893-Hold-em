// Trim Shippori Mincho B1 to the subsets this UI actually draws.
//
// Fontsource ships the Japanese face as ~120 unicode-range slices per weight;
// declaring all of them costs ~150 kB of render-blocking CSS per weight. The
// UI's kanji are a fixed set, so we scan the client source for CJK characters
// and keep only the slices that contain them, plus Latin. Anything else (a
// kanji player name, say) falls back to the system Mincho.
//
// Two files come out:
//   src/client/styles/fonts.css   the app's own kanji (loaded up front)
//   src/client/story/fonts.css    the extra slices the story layer draws
//                                 (masks, seals, stamps), loaded with it
//
//   node scripts/fonts.mjs          # rewrite both
//   node scripts/fonts.mjs --check  # exit 1 if either is stale (CI)
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const APP_OUT = join(root, 'src/client/styles/fonts.css');
const STORY_DIR = join(root, 'src/client/story');
const STORY_OUT = join(STORY_DIR, 'fonts.css');
const WEIGHTS = [500, 800];
const PKG = '@fontsource/shippori-mincho-b1';
const CJK = /[　-ヿ㐀-䶿一-鿿＀-￯]/gu;

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : /\.(tsx?|css)$/.test(f) ? [p] : [];
  });
}

function scan(files) {
  const used = new Set();
  for (const file of files) {
    if (file === APP_OUT || file === STORY_OUT) continue;
    for (const ch of readFileSync(file, 'utf8').match(CJK) ?? []) used.add(ch.codePointAt(0));
  }
  return used;
}

function covers(range, cps) {
  return range.split(',').some((part) => {
    const m = /U\+([0-9a-f]+)(?:-([0-9a-f]+))?/i.exec(part.trim());
    if (!m) return false;
    const lo = parseInt(m[1], 16);
    const hi = m[2] ? parseInt(m[2], 16) : lo;
    for (const cp of cps) if (cp >= lo && cp <= hi) return true;
    return false;
  });
}

/** Every slice, by weight: its name, its range, and its CSS. */
const slices = WEIGHTS.flatMap((w) => {
  const src = readFileSync(join(root, 'node_modules', PKG, `${w}.css`), 'utf8');
  return src
    .split(/(?=\/\* shippori)/)
    .filter((block) => block.includes('@font-face'))
    .map((block) => ({
      name: /\/\* (\S+) \*\//.exec(block)?.[1] ?? '',
      range: /unicode-range:\s*([^;]+);/.exec(block)?.[1] ?? '',
      css: block.replaceAll('url(./files/', `url(${PKG}/files/`).trim(),
    }));
});

const chars = (cps) =>
  [...cps]
    .sort((a, b) => a - b)
    .map((c) => String.fromCodePoint(c))
    .join('');

const allFiles = [...walk(join(root, 'src')), join(root, 'index.html')];
const appUsed = scan(allFiles.filter((f) => !f.startsWith(STORY_DIR)));
const storyUsed = scan(allFiles.filter((f) => f.startsWith(STORY_DIR)));

const appSlices = slices.filter((s) => s.name.includes('-latin-') || covers(s.range, appUsed));
const storySlices = slices.filter((s) => !appSlices.includes(s) && covers(s.range, storyUsed));

const appCss =
  `/* Generated by scripts/fonts.mjs from ${PKG}. Do not edit by hand. */\n/* Kanji in use: ${chars(appUsed)} */\n` +
  appSlices.map((s) => s.css + '\n\n').join('');
const storyCss =
  `/* Generated by scripts/fonts.mjs from ${PKG}. Do not edit by hand. */\n` +
  `/* The story layer's slices, beyond the app's own (src/client/styles/fonts.css). */\n` +
  `/* Kanji in use: ${chars(storyUsed)} */\n` +
  storySlices.map((s) => s.css + '\n\n').join('');

const outputs = [
  [APP_OUT, appCss, appSlices.length, appUsed.size],
  [STORY_OUT, storyCss, storySlices.length, storyUsed.size],
];

if (process.argv.includes('--check')) {
  let stale = false;
  for (const [file, css] of outputs) {
    let current = '';
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      // Missing counts as stale.
    }
    if (current !== css) {
      console.error(`${file.slice(root.length + 1)} is stale. Run: node scripts/fonts.mjs`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log('fonts are current');
} else {
  for (const [file, css, kept, used] of outputs) {
    writeFileSync(file, css);
    console.log(`${file.slice(root.length + 1)}: kept ${kept} font-face slices for ${used} CJK characters`);
  }
}
